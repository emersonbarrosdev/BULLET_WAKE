"""Mechanical asset packing and alpha-profile measurement; no painting or chroma removal."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

parser = argparse.ArgumentParser()
parser.add_argument('--coast', required=True, type=Path)
parser.add_argument('--water', required=True, type=Path)
parser.add_argument('--wake', required=True, type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
out = root / 'public/assets/arcade/pelagic-review'
out.mkdir(exist_ok=True)
im = Image.open(args.coast).convert('RGBA')
atlas = Image.new('RGBA', (3072, 1536))
profiles = []
extras=[('pelagic-archipelago.webp',0),('pelagic-archipelago.webp',4),('pelagic-coast.webp',6),('pelagic-archipelago.webp',3)]
for frame in range(8):
    if frame<4:
        x, y = frame % 2, frame // 2
        cell = im.crop((x*im.width//2, y*im.height//2, (x+1)*im.width//2, (y+1)*im.height//2))
    else:
        filename,index=extras[frame-4]
        source=Image.open(out.parent/filename).convert('RGBA')
        x,y=index%4,index//4
        cell=source.crop((x*512,y*512,(x+1)*512,(y+1)*512))
    # Uniform fit preserves perspective. The original generated alpha is untouched.
    cell.thumbnail((752, 752), Image.Resampling.LANCZOS)
    packed = Image.new('RGBA', (768, 768))
    packed.alpha_composite(cell, ((768-cell.width)//2, (768-cell.height)//2))
    atlas.alpha_composite(packed, ((frame%4)*768, (frame//4)*768))
    alpha = packed.getchannel('A')
    rows = []
    for row in range(96):
        occupied = [xx for yy in range(row*8, (row+1)*8) for xx in range(768) if alpha.getpixel((xx, yy)) > 100]
        rows.append([round(min(occupied)/768, 4), round((max(occupied)+1)/768, 4)] if occupied else [1, 0])
    profiles.append(rows)
atlas.save(out/'formations.webp', lossless=True)
water = Image.open(args.water).convert('RGB').resize((1024, 1024), Image.Resampling.LANCZOS)
water.save(out/'water.webp', lossless=True)
wake_source=Image.open(args.wake).convert('RGBA')
wakes=Image.new('RGBA',(1024,512))
for frame in range(4):
    cell=wake_source.crop((frame*wake_source.width//4,0,(frame+1)*wake_source.width//4,wake_source.height))
    wakes.alpha_composite(cell.resize((256,512),Image.Resampling.LANCZOS),(frame*256,0))
wakes.save(out/'wakes.webp',lossless=True)
(root/'src/game/arcade/PelagicAlphaProfiles.ts').write_text(
    '// Generated by pack-pelagic-review.py from the exact rendered alpha. Do not hand edit.\n'
    'export const COAST_ALPHA_PROFILES: ReadonlyArray<ReadonlyArray<readonly [number,number]>> = '
    + json.dumps(profiles, separators=(',', ':')) + ';\n', encoding='utf-8')
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
(out/'manifest.json').write_text(json.dumps({
    'generator': 'native imagegen', 'packing': 'uniform resampling only; original alpha preserved',
    'sources': [{'file': p.name, 'sha256': sha(p)} for p in [args.coast,args.water,args.wake,out.parent/'pelagic-archipelago.webp',out.parent/'pelagic-coast.webp']],
    'outputs': [{'file': p.name, 'sha256': sha(p)} for p in [out/'formations.webp',out/'water.webp',out/'wakes.webp']],
}, indent=2), encoding='utf-8')
print(out)
