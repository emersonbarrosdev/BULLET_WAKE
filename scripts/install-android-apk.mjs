import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { homedir } from 'node:os';
const sdk = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT ?? join(homedir(), 'AppData/Local/Android/Sdk');
const adb = join(sdk, 'platform-tools', process.platform === 'win32' ? 'adb.exe' : 'adb');
const apk = resolve('output/android/BULLET_WAKE-hull-preview.apk');
const packageId = 'dev.emersonbarros.bulletwake.preview';
if (!existsSync(apk)) throw new Error('Generate the APK with npm run android:apk first.');
const run = args => execFileSync(adb, args, { encoding: 'utf8', windowsHide: true, timeout: 180000 });
console.log('Waiting for an Android device with USB debugging authorized (up to 10 minutes)...');
execFileSync(adb, ['wait-for-device'], { stdio: 'inherit', windowsHide: true, timeout: 600000 });
const devices = run(['devices']).split(/\r?\n/).map(line => line.trim().split(/\s+/)).filter(parts => parts[1] === 'device');
if (devices.length !== 1) throw new Error('Exactly one authorized device is required; no device was modified.');
const serial = devices[0][0], target = args => run(['-s', serial, ...args]);
const sdkVersion = Number(target(['shell', 'getprop', 'ro.build.version.sdk']).trim());
if (sdkVersion < 28) throw new Error('This test APK requires Android 9 or newer.');
const install = target(['install', '-r', apk]);
console.log(install.trim());
if (!install.includes('Success')) throw new Error('Installation did not report success. Existing apps were not uninstalled.');
const launch = target(['shell', 'am', 'start', '-W', '-n', packageId + '/.MainActivity']);
console.log(launch.trim());
const path = target(['shell', 'pm', 'path', packageId]).trim();
if (!path.startsWith('package:') || !launch.includes('Status: ok')) throw new Error('Installed but launch could not be confirmed.');
const build = JSON.parse(readFileSync(resolve('output/android/build-report.json'), 'utf8'));
const report = { installed:true, launched:true, packageId, androidSdk:sdkVersion, model:target(['shell','getprop','ro.product.model']).trim(), sha256:build.sha256, installedAt:new Date().toISOString() };
writeFileSync(resolve('output/android/install-report.json'), JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
